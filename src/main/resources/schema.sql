-- CU-RH-02 Gestionar asignación de horarios laborales
CREATE TABLE IF NOT EXISTS horario_laboral (
    id_horario  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INT         NOT NULL REFERENCES empleado (id_empleado),
    dia         VARCHAR(10) NOT NULL,
    hora_inicio TIME        NOT NULL,
    hora_fin    TIME        NOT NULL
);

-- CU-RH-05 Gestionar solicitud y aprobación de vacaciones
CREATE TABLE IF NOT EXISTS solicitud_vacaciones (
    id_solicitud   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado    INT          NOT NULL REFERENCES empleado (id_empleado),
    fecha_inicio   DATE         NOT NULL,
    fecha_fin      DATE         NOT NULL,
    dias_habiles   INT          NOT NULL,
    observacion    VARCHAR(200),
    estado         VARCHAR(10)  NOT NULL,
    id_aprobador   INT          REFERENCES empleado (id_empleado),
    fecha_decision DATE,
    motivo_rechazo VARCHAR(200)
);

-- CU-MF-05 Diagnosticar y reparar vehículo: datos del diagnóstico en la orden
ALTER TABLE orden_mantenimiento ADD COLUMN IF NOT EXISTS diagnostico VARCHAR(500);
ALTER TABLE orden_mantenimiento ADD COLUMN IF NOT EXISTS horas_mano_obra DECIMAL(6,2) DEFAULT 0 NOT NULL;

-- CU-MF-05: repuestos que necesita cada orden; descontado indica si ya salieron del inventario
CREATE TABLE IF NOT EXISTS orden_repuesto (
    id_orden_repuesto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden          INT     NOT NULL REFERENCES orden_mantenimiento (id_orden),
    id_repuesto       INT     NOT NULL REFERENCES repuesto (id_repuesto),
    cantidad          INT     NOT NULL,
    descontado        BOOLEAN NOT NULL
);

-- CU-MF-04 Gestionar historial de mantenimiento del vehículo
CREATE TABLE IF NOT EXISTS historial_mantenimiento (
    id_registro INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vehiculo INT           NOT NULL REFERENCES vehiculo (id_vehiculo),
    id_orden    INT           REFERENCES orden_mantenimiento (id_orden),
    fecha       DATE          NOT NULL,
    kilometraje INT           NOT NULL,
    descripcion VARCHAR(300)  NOT NULL,
    costo       DECIMAL(12,2) NOT NULL
);
