-- Esquema de la base de datos H2 para Recursos Humanos y Mantenimiento y Flota

CREATE TABLE IF NOT EXISTS empleado (
    id_empleado   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento     VARCHAR(15)  NOT NULL UNIQUE,
    nombres       VARCHAR(80)  NOT NULL,
    apellidos     VARCHAR(80)  NOT NULL,
    cargo         VARCHAR(60)  NOT NULL,
    telefono      VARCHAR(15),
    correo        VARCHAR(100),
    fecha_ingreso DATE         NOT NULL,
    estado        VARCHAR(10)  NOT NULL
);

CREATE TABLE IF NOT EXISTS contrato_laboral (
    id_contrato  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado  INT           NOT NULL REFERENCES empleado (id_empleado),
    tipo         VARCHAR(25)   NOT NULL,
    fecha_inicio DATE          NOT NULL,
    fecha_fin    DATE,
    salario      DECIMAL(12,2) NOT NULL,
    estado       VARCHAR(12)   NOT NULL
);

CREATE TABLE IF NOT EXISTS permiso_laboral (
    id_permiso  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INT          NOT NULL REFERENCES empleado (id_empleado),
    fecha_inicio DATE        NOT NULL,
    fecha_fin    DATE        NOT NULL,
    motivo       VARCHAR(200) NOT NULL,
    soporte      VARCHAR(255),
    estado       VARCHAR(12)  NOT NULL
);

CREATE TABLE IF NOT EXISTS vehiculo (
    id_vehiculo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa       VARCHAR(6)  NOT NULL UNIQUE,
    marca       VARCHAR(40) NOT NULL,
    modelo      VARCHAR(40) NOT NULL,
    tipo        VARCHAR(15) NOT NULL,
    anio        INT         NOT NULL,
    estado      VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS tecnico (
    id_tecnico   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado  INT         NOT NULL UNIQUE REFERENCES empleado (id_empleado),
    especialidad VARCHAR(60) NOT NULL,
    disponible   BOOLEAN     NOT NULL
);

CREATE TABLE IF NOT EXISTS repuesto (
    id_repuesto  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(20)   NOT NULL UNIQUE,
    nombre       VARCHAR(80)   NOT NULL,
    cantidad     INT           NOT NULL,
    stock_minimo INT           NOT NULL,
    precio       DECIMAL(12,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS orden_mantenimiento (
    id_orden       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vehiculo    INT          NOT NULL REFERENCES vehiculo (id_vehiculo),
    id_tecnico     INT          NOT NULL REFERENCES tecnico (id_tecnico),
    fecha_apertura DATE         NOT NULL,
    fecha_cierre   DATE,
    motivo         VARCHAR(200) NOT NULL,
    kilometraje    INT          NOT NULL,
    prioridad      VARCHAR(10)  NOT NULL,
    estado         VARCHAR(20)  NOT NULL
);
